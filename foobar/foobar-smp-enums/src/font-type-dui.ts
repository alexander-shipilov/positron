/**
 * The {@link FontTypeDUI} enumeration specifies the `Default UI` font types.
 *
 * @public
 */
export enum FontTypeDUI {
  /**
   * Default font
   */
  Default = 0,

  /**
   * Tabs font
   */
  Tabs = 1,

  /**
   * Lists font
   */
  Lists = 2,

  /**
   * Playlists font
   */
  Playlists = 3,

  /**
   * Status Bar font
   */
  Statusbar = 4,

  /**
   * Console font
   */
  Console = 5,
}

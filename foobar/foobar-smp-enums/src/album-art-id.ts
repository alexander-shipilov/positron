/**
 * The {@link AlbumArtId} enumeration represents album art types.
 *
 * @public
 */
export const enum AlbumArtId {
  /**
   * Front art.
   */
  Front = 0,

  /**
   * Back art.
   */
  Back = 1,

  /**
   * Disc art.
   */
  Disc = 2,

  /**
   * Icon art.
   */
  Icon = 3,

  /**
   * Artist art.
   */
  Artist = 4,
}

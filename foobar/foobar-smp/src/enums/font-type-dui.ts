/**
 * The {@link FontTypeDui} enumeration specifies Default UI font types.
 * This enumeration is used by {@link Window.GetFontDUI}
 *
 * @public
 */
export enum FontTypeDui {
  /**
   * Default font
   */
  Default = 0,

  /**
   * Tabs font
   */
  Tabs = 1,

  /**
   * Lists font
   */
  Lists = 2,

  /**
   * Playlists font
   */
  Playlists = 3,

  /**
   * Status Bar font
   */
  Statusbar = 4,

  /**
   * Console font
   */
  Console = 5,
}

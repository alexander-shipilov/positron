/**
 * The {@link BitmapFormat} enumeration represents bitmap output formats.
 *
 * @remarks
 * The {@link BitmapFormat} enumeration is used by:
 * {@link GdiBitmap.SaveAs}.
 *
 * @public
 */
export enum BitmapFormat {
  Bmp = "image/bmp",
  Gif = "image/gif",
  Jpeg = "image/jpeg",
  Png = "image/png",
  Tiff = "image/tiff",
}

/**
 * The {@link ColourTypeDui} enumeration specifies `Default UI` colors types.
 *
 * @remarks
 * The {@link ColourTypeDui} enumeration is used by:
 * {@link FbWindow.GetColourDUI}.
 *
 * @public
 */
export enum ColourTypeDui {
  /**
   * Text color
   */
  Text = 0,

  /**
   * Background color
   */
  Background = 1,

  /**
   * Highlight color
   */
  Highlight = 2,

  /**
   * Selection color
   */
  Selection = 3,
}

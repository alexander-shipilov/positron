/**
 * The {@link NumericalSign} enumeration represents the explicit sign character
 * of a numeric CSS token.
 *
 * @public
 */
export enum NumericalSign {
  /**
   * The {@link NumericalSign.Minus} member indicates an explicit `-` sign.
   */
  Minus = "-",

  /**
   * The {@link NumericalSign.Plus} member indicates an explicit `+` sign.
   */
  Plus = "+",
}
